/* Prüfung: Jeder Buchungssatz muss Soll = Haben erfüllen. */
export function summe(zeilen) {
  return Math.round(zeilen.reduce((s, z) => s + z.betrag, 0) * 100) / 100;
}
export function istAusgeglichen(buchung) {
  return Math.abs(summe(buchung.soll) - summe(buchung.haben)) < 0.005;
}
