import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { fgoGesetzQuelle, fgoSeitenReview } from '../../src/data/endriss-fgo-seitenreview.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const source = JSON.parse(fs.readFileSync(path.join(root, 'public/endriss/quellen/sources/ao-fgo.json'), 'utf8'));
for (const field of ['driveId', 'sourceBytes', 'sha256']) assert.equal(source[field], fgoGesetzQuelle[field], `Source identity: ${field}`);
assert.equal(source.pages.length, 37);
assert.deepEqual(fgoSeitenReview.map(r => r.page), Array.from({ length: 36 }, (_, i) => i + 2));
const outputPath = path.join(root, 'src/data/endriss-fgo-gesetz.generated.js');
const hash = text => createHash('sha256').update(text).digest('hex');
const normalize = text => text.replace(/\s+/g, ' ').trim();
const removals = [];

// This is an exact, auditable transformation of the ALREADY available text layer.
// No OCR service and no current-law source is called. Individual artifact repairs
// are permitted only where a human-readable original image was directly checked.
const pages = fgoSeitenReview.map(review => {
  assert.equal(review.imageReviewed, true);
  const original = source.pages.find(p => p.page === review.page);
  assert.ok(original && typeof original.text === 'string');
  let text = original.text.split('\n').map(line => line.trim().replace(/ {2,}/g, ' ')).join('\n');
  for (const [before, after] of review.bereinigungen) {
    assert.ok(before && before !== after, `Invalid repair on page ${review.page}`);
    assert.equal(text.split(before).length - 1, 1, `Page ${review.page}: expected one exact artifact ${JSON.stringify(before)}`);
    text = text.replace(before, after);
    removals.push({ page: review.page, before, after });
  }
  let serviceLines = 0;
  text = text.split('\n').filter(line => {
    if (line.includes('Ein Service des Bundesministeriums der Justiz sowie des Bundesamts für') || line.includes('Justiz ‒ www.gesetze-im-internet.de')) {
      serviceLines++;
      return false;
    }
    return true;
  }).join('\n').trim();
  assert.equal(serviceLines, 2, `Page ${review.page}: exact repeating service header`);
  // Paragraphs and original enumerations stay separate readable native blocks.
  // A page boundary does NOT invent a missing sentence or repeat a paragraph.
  const blocks = text.split(/\n\s*\n/).flatMap(part => part.split(/\n(?=(?:\d+\.|[a-z]\))\s)/)).map(part => {
    const value = normalize(part);
    const heading = /^§{1,2}\s*\d+[a-z]?(?:\s+(?:bis|und)\s+\d+)?(?:\s+\(weggefallen\))?$/.test(value)
      || /^(?:Erster|Zweiter|Dritter|Vierter) Teil$/.test(value)
      || /^(?:Abschnitt [IVX]+|Unterabschnitt \d+)$/.test(value);
    return { typ: heading ? 'titel' : 'text', text: value };
  }).filter(b => b.text);
  assert.ok(blocks.length >= 5, `Page ${review.page}: suspiciously empty source transfer`);
  assert.equal(normalize(blocks.map(b => b.text).join(' ')), normalize(text), `Page ${review.page}: layout must not change source words`);
  assert.ok(!/Persönliches PDF|Yusuf|51429|534710|11000|3571275|mummer|gezoomen|Zustellung00des/.test(text), `Page ${review.page}: unhandled owner/OCR residue`);
  return { page: review.page, printedPage: review.printedPage, imageSha256: original.imageSha256,
    originalTextSha256: hash(original.text), textSha256: hash(normalize(text)), blocks };
});
const generated = `/* Generated by tools/endriss/vorbereiten-fgo-gesetz.mjs.\n   Printed source text only; annotations are separate in endriss-fgo-seitenreview.js.\n   Historical source amendment: 10.03.2023. No legal-currency review. */\nexport const fgoGesetzSeiten = ${JSON.stringify(pages, null, 2)};\n`;
if (process.argv.includes('--check')) {
  assert.equal(fs.readFileSync(outputPath, 'utf8'), generated, 'Committed FGO text differs from the source-bound reproducible transfer');
} else {
  fs.writeFileSync(outputPath, generated);
}
const report = {
  sourceId: source.id, driveId: source.driveId, sourceSha256: source.sha256,
  physicalPages: 37, statutePagesTransferred: pages.length,
  originalImagesChanged: false, legalReview: false,
  output: path.relative(root, outputPath), outputSha256: hash(generated),
  sourcePageRecords: pages.map(({ blocks, ...entry }) => ({ ...entry, nativeBlocks: blocks.length })),
  exactTextLayerRepairs: removals,
  annotationRows: fgoSeitenReview.reduce((n, p) => n + p.notizen.length, 0),
  note: 'Page counts and reproducibility are technical checks. Direct visual review is separately recorded per page; this report is not a legal opinion.',
};
fs.mkdirSync(path.join(root, 'test-results/endriss-fgo-gesetz'), { recursive: true });
fs.writeFileSync(path.join(root, 'test-results/endriss-fgo-gesetz/transfer.json'), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report, null, 2));
